-- الشواهد المطلوبة غير المرفوعة (برامج الخطة والاستدامة)، والمطابقة بعنوان مقارب كما في البوابة
create or replace function public.acc_norm(t text) returns text language sql immutable as $$
  select trim(regexp_replace(translate(coalesce(t, ''), 'أإآةى', 'اااهي'), '[^[:alnum:][:space:]]', ' ', 'g'));
$$;
create or replace function public.acc_missing(p_domains int[])
returns table (code text, title text) language sql stable security definer set search_path = public as $$
  select g.code, t.title
    from acc_programs g
    join acc_plans p on p.id = g.plan_id and p.status = 'active'
    cross join lateral unnest(g.evidence) as t(title)
   where g.kind in ('plan', 'sustain') and g.domain = any(p_domains)
     and not exists (select 1 from acc_evidence e where e.code = g.code
       and (acc_norm(e.title) = acc_norm(t.title)
         or (least(length(acc_norm(e.title)), length(acc_norm(t.title))) >= 8
             and (position(acc_norm(e.title) in acc_norm(t.title)) > 0 or position(acc_norm(t.title) in acc_norm(e.title)) > 0))));
$$;
revoke all on function public.acc_missing(int[]) from public, anon;

