-- ---------------------------------------------------------------------
--  الجدول الدراسي: كل فصل له حصة رياضيات وحصة عربي يوميًا (الأحد–الخميس)
--  فصل الصف g: الرياضيات في الحصة g، والعربي في الحصة g+3 — فلا يتعارض
--  معلم مع نفسه، وتوجد حصص في كل أيام الأسبوع للتجربة.
-- ---------------------------------------------------------------------
insert into public.schedule (teacher_id, subject_id, class_id, day_of_week, period_no, academic_year, term)
select t.teacher_id::uuid, t.subject_id::uuid, c.id, d.dow, t.period_no, '1448', 1
from public.classes c
cross join generate_series(1, 5) as d(dow)
cross join lateral (values
  ('00000000-0000-4000-b000-000000000011', '00000000-0000-4000-c000-00000000010' || c.grade, c.grade),
  ('00000000-0000-4000-b000-000000000012', '00000000-0000-4000-c000-00000000020' || c.grade, c.grade + 3)
) as t(teacher_id, subject_id, period_no)
where c.academic_year = '1448' and c.id::text like '00000000-0000-4000-d000-%'
on conflict do nothing;

