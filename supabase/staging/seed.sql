insert into public.period_times (season, kind, period_no, label, start_time, end_time, sort_order)
select s.season, t.kind, t.period_no, t.label, t.start_time::time, t.end_time::time, t.sort_order
from (values ('summer'), ('winter'), ('ramadan')) as s(season)
cross join (values
  ('period', 1, 'الحصة الأولى',  '07:00', '07:45', 1),
  ('period', 2, 'الحصة الثانية', '07:45', '08:30', 2),
  ('period', 3, 'الحصة الثالثة', '08:30', '09:15', 3),
  ('break',  null, 'الفسحة',     '09:15', '09:40', 4),
  ('period', 4, 'الحصة الرابعة', '09:40', '10:25', 5),
  ('period', 5, 'الحصة الخامسة', '10:25', '11:10', 6),
  ('period', 6, 'الحصة السادسة', '11:10', '11:55', 7),
  ('period', 7, 'الحصة السابعة', '11:55', '12:40', 8)
) as t(kind, period_no, label, start_time, end_time, sort_order)
where not exists (select 1 from public.period_times p where p.season = s.season);

