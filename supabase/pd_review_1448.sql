  ('PD-1448-1449-0069', 'revoke', 'عدم مطابقته للشروط: تنفيذ البرنامج التدريبي يعتمده المعهد الوطني ولا يُعتمد في المدرسة، وبلا مرفق.'),
  ('PD-1448-1449-0070', 'revoke', 'عدم مطابقته للشروط: حضور برنامج نفّذه زميل يُحتسب للحاضرين تلقائيًا، ووُثّق معه تنفيذ تدريب للفريق نفسه.'),
