-- توحيد الاسم: الهمزات والتاء المربوطة والألف المقصورة و«عبد ال» و«بن»
drop table if exists plc_norm;
create temp table plc_norm as
select t.id, array_remove(string_to_array(btrim(regexp_replace(translate(replace(replace(t.full_name, 'عبد ', 'عبد'), 'ـ', ''),
         'أإآةى', 'اااهي'), '\s+', ' ', 'g')), ' '), 'بن') as tk
  from public.teachers t;

drop table if exists plc_match;
create temp table plc_match as
select s.dept, s.name, s.head,
       array_remove(string_to_array(translate(replace(s.name, 'عبد ', 'عبد'), 'أإآةى', 'اااهي'), ' '), 'بن') as tk
  from plc_seed s;

drop table if exists plc_hit;
create temp table plc_hit as
select m.dept, m.name, m.head, array_agg(n.id) as ids
  from plc_match m
  left join plc_norm n on n.tk[1] = m.tk[1] and m.tk[2] = any(n.tk) and m.tk[array_length(m.tk, 1)] = any(n.tk)
 group by m.dept, m.name, m.head;

insert into public.department_members (department_id, teacher_id, is_head)
select d.id, h.ids[1], h.head
  from plc_hit h join public.departments d on d.name = h.dept
 where array_length(array_remove(h.ids, null), 1) = 1
on conflict (department_id, teacher_id) do update set is_head = excluded.is_head;

-- ما لم يُربط: يُضاف من صفحة «الأقسام» في التطوير المهني
select h.dept as "القسم", h.name as "الاسم",
       case when array_length(array_remove(h.ids, null), 1) is null then 'لم يُعثر عليه' else 'أكثر من معلم بهذا الاسم' end as "الحالة"
  from plc_hit h
 where coalesce(array_length(array_remove(h.ids, null), 1), 0) <> 1
 order by 1, 2;
