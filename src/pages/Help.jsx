const hijriToday = () => {
  try {
    const p = new Intl.DateTimeFormat("en-u-ca-islamic-umalqura",
      { day: "2-digit", month: "2-digit", year: "numeric" }).formatToParts(new Date());
    const g = (t) => p.find((x) => x.type === t)?.value ?? "";
    return `${g("day")}/${g("month")}/${String(g("year")).replace(/\D/g, "")}هـ`;
  } catch { return ""; }
};

