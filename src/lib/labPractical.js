/** مهام التدريب الآلية من الدروس: { id, grade, unit, lesson, title, widget, task } */
export function autoTasks() {
  const out = [];
  LESSONS.forEach((l) => l.stations.forEach((s) => {
    if (s.type !== "practice") return;
    s.tasks.forEach((task, k) => out.push({ id: `${l.id}:${s.id}:${k}`, grade: gradeOfLesson(l), unit: l.unit.no, lesson: l.id,
      lessonTitle: l.lesson.title, title: s.title, widget: s.widget, task }));
  }));
  return out;
}

