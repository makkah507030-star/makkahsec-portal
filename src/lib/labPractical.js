/** درجات المعايير بعد تحويل نقاطها لدرجة الجزء، بأنصاف الدرجة والفرق على آخر معيار */
export function scaleCriteria(card, marks) {
  const sum = card.criteria.reduce((a, c) => a + c.w, 0) || 1;
  const out = card.criteria.map((c) => ({ t: c.t, m: Math.round((c.w / sum) * marks * 2) / 2 }));
  const diff = Math.round((marks - out.reduce((a, c) => a + c.m, 0)) * 2) / 2;
  if (out.length) out[out.length - 1].m += diff;
  return out;
}

/** بطاقة الطالب بالقرعة: ثابتة للطالب في الاختبار، وموزعة على البطاقات بالتساوي داخل الفصل */
export function cardFor(exam, studentIds, studentId) {
  const cards = exam.body?.cards ?? [];
  if (!cards.length) return null;
  const order = shuffle(studentIds, `${exam.code}:cards`);
  const offset = Math.floor(Math.abs([...exam.code].reduce((a, c) => a + c.charCodeAt(0), 0)) % cards.length);
  return cards[(order.indexOf(studentId) + offset) % cards.length];
}
