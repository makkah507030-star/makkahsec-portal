/* الأرقام بعد حرف عربي تُعامَل أرقامًا عربية فتنعكس مع ما يلاصقها: «25%» تظهر «%25»، ورمز المؤشر
   «1-2-1-2» يظهر «2-1-2-1». تُعزل هذه داخل النص اتجاهًا من اليسار (LRI … PDI) فتظهر كما كُتبت.
   تُستعمل للنصوص المركّبة: العناوين الفرعية للبطاقات، و«أبرز ما في التقرير»، والرسائل. */
const RE = /\d+(?:-\d+){3}|[+-]?\d+(?:[.,]\d+)?\s?%/g;
export const bidi = (t) => (typeof t === "string" ? t.replace(RE, (m) => `⁦${m}⁩`) : t);
