export function countAr(n, noun, { acc = false } = {}) {
  const f = NOUNS[noun];
  const v = Number(n) || 0;
  if (v === 1) return f.one;
  if (v === 2) return f.two[acc ? 1 : 0];
  if (v >= 3 && v <= 10) return `${v} ${f.few}`;
  return `${v} ${f.many}`;
}
