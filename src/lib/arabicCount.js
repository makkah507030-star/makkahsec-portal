// المفرد المجرور بعد المئة والألف («100 طالب»): صيغة 11–99 بلا تنوين النصب
const sing = (f) => f.many.replace(/(ًا|ً)(?=\s|$)/, "");

export function countAr(n, noun, { acc = false } = {}) {
  const f = NOUNS[noun];
  const v = Number(n) || 0;
  if (v === 1) return f.one;
  if (v === 2) return f.two[acc ? 1 : 0];
  return `${v} ${nounAr(v, noun)}`;
}

/** المعدود وحده بصيغته للعدد، لما يُكتب رقمه منفصلًا (رقم كبير فوقه اسمه):
 *  1 → «برنامج»، 2 → «برنامجان»، 3–10 → «برامج»، 11–99 → «برنامجًا»، 100 و200… و101 و102 → «برنامج»،
 *  وما بعد المئة يتبع آخر جزأيه (103 → «برامج»، 111 → «برنامجًا»). */
export function nounAr(n, noun, { acc = false } = {}) {
  const f = NOUNS[noun];
  const v = Number(n) || 0;
  const r = v > 100 ? v % 100 : v;
  if (v === 1) return sing(f);
  if (v === 2) return f.two[acc ? 1 : 0];
  if (r >= 3 && r <= 10) return f.few;
  if (r >= 11 && r <= 99) return f.many;
  return v === 0 ? f.few : sing(f);
}
