/** موعد النشاط: تاريخه، وإلا وصفه (شهر أو «وفق المناسبات») */
export const dueOf = (a) => a.due_date || a.due_label || "—";
const MONTHS = { "سبتمبر": 9, "أكتوبر": 10, "نوفمبر": 11, "ديسمبر": 12 };
/** هل فات موعد النشاط ولم يكتمل: بتاريخه، أو بانتهاء شهره */
export function overdue(a, today = new Date()) {
  if (a.status === "done" || a.status === "later") return false;
  if (a.due_date) return new Date(`${a.due_date}T23:59:59`) < today;
  const m = MONTHS[a.due_label];
  return m ? new Date(2026, m, 0, 23, 59, 59) < today : false;
}

