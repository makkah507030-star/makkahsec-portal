export const pdStages = (kind) => PD_KINDS[kind]?.attendees
  ? [{ key: "info", t: "البيانات" }, { key: "content", t: "المحتوى" }, { key: "attendees", t: "الحاضرون" },
     { key: "files", t: "الشواهد" }, { key: "signing", t: "توقيع الحاضرين" }, { key: "approval", t: "الاعتماد" }]
  : [{ key: "info", t: "البيانات" }, { key: "content", t: "التفاصيل" }, { key: "files", t: "المرفقات" },
     { key: "approval", t: "الرفع والاعتماد" }];

export function pdMissing(key, r) {
  const k = PD_KINDS[r?.kind];
  const d = r?.data ?? {};
  if (!k) return [];
  if (key === "info" || key === "content") return k[key].filter((f) => f.required && !String(d[f.key] ?? "").trim()).map((f) => f.t);
  if (key === "attendees") return (r.attendees ?? []).length ? [] : ["الحاضرون"];
  return [];
}
