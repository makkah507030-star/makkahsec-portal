// ملفات الاختبارات في المجلد نفسه (gatsft.js علمي، gataft.js نظري)، تُحمَّل عند فتح المركز
const SETS = Object.values(import.meta.glob("./gat*ft.js"));

let bankP = null;
/* كل الأسئلة الرسمية في قائمة واحدة، مع القطعة أو الجدول المشترك وروابط الصور */
export function loadBank() {
  bankP ??= Promise.all(SETS.map((f) => f())).then((mods) => mods.flatMap(({ default: x }) =>
    x.questions.map((q) => {
      const g = q.group ? x.groups?.[q.group] : null;
      return {
        ...q, key: `${x.code}-${q.n}`, set: x.code, setTitle: x.title,
        img: q.img ? `/qudrat/${q.img}` : null,
        passage: g ? { key: `${x.code}:${q.group}`, title: g.title ?? null,
                       text: Array.isArray(g.text) ? g.text : g.text ? [g.text] : [],
                       img: g.img ? `/qudrat/${g.img}` : null } : null,
      };
    })));
  return bankP;
}

