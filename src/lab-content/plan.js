const iso = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

/** بند الخطة الحالي لتاريخ اليوم (أسبوع دراسي أو إجازة أو اختبارات)، والجمعة والسبت يتبعان الأسبوع القادم */
export function currentPlanItem(today = new Date()) {
  const t = iso(today);
  const exact = PLAN.find((w) => w.from <= t && t <= w.to);
  if (exact) return exact;
  return PLAN.find((w) => w.from > t) ?? null;
}

/** أسابيع الدرس في التوزيع: [] إن لم يرد فيه */
export function weeksOfLesson(id) {
  return PLAN.filter((w) => w.no && [...(w.g10 ?? []), ...(w.g12 ?? [])].includes(id)).map((w) => w.no);
}
export const weeksLabel = (ws) => (!ws.length ? "" : ws.length === 1 ? `الأسبوع ${ws[0]}` : `الأسابيع ${ws[0]}–${ws[ws.length - 1]}`);
